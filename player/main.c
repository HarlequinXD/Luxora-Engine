/* Luxora player: the runtime that ships with built games. It loads the bundled project
 * (project.lxproj + Assets) and runs the startup scene. Game scripts are compiled in. */
#include <luxora/luxora.h>
#include <stdio.h>
#include <string.h>

void lx_game_register_scripts(void); /* generated by CMake from Assets/Scripts */

static char g_project[LX_PATH_MAX];

int lx_main(int argc, char **argv) {
    const char *dir = NULL;
    for (int i = 1; i < argc; i++)
        if (argv[i][0] != '-') dir = argv[i];
#if defined(__ANDROID__)
    dir = "apk:/Data";
#else
    if (!dir) {
        /* default: Data/ next to the executable, else the current folder */
        char exe_dir[LX_PATH_MAX] = ".";
        if (lx_exe_dir()[0]) lx_strcpy(exe_dir, sizeof exe_dir, lx_exe_dir());   /* works however it was launched */
        else if (argc > 0) lx_path_parent(exe_dir, sizeof exe_dir, argv[0]);
        if (!exe_dir[0]) strcpy(exe_dir, ".");
        lx_path_join(g_project, sizeof g_project, exe_dir, "Data");
        dir = lx_dir_exists(g_project) ? g_project : ".";
    }
#endif
    LxAppDesc app;
    memset(&app, 0, sizeof app);
    app.title = "Luxora Game";
    app.project_dir = dir;
    app.on_init = lx_game_register_scripts;
    return lx_run(&app);
}

#if !defined(__ANDROID__)
int main(int argc, char **argv) { return lx_main(argc, argv); }
#endif
