#!/usr/bin/env python3
"""Generates src/script/script_api_table.h: every function declared in include/luxora/luxora.h,
so compiled game scripts can call the engine. Run after changing the public API:
    python3 tools/gen_script_api.py           (rewrite)
    python3 tools/gen_script_api.py --check   (fail if out of date; used by CI)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, 'include', 'luxora', 'luxora.h')
OUT = os.path.join(ROOT, 'src', 'script', 'script_api_table.h')
# declared for the editor/tools but not part of the runtime library, or not callable from scripts
EXCLUDE = {'lx_main'}


def functions(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    text = re.sub(r'//[^\n]*', ' ', text)
    text = re.sub(r'\\\n', ' ', text)
    lines = [l for l in text.split('\n') if not l.lstrip().startswith('#')]
    text = '\n'.join(lines).replace('extern "C" {', ' ')
    names, depth, stmt = [], 0, ''
    for ch in text:
        if ch == '{':
            depth += 1
            stmt = ''
            continue
        if ch == '}':
            depth = max(0, depth - 1)
            stmt = ''
            continue
        if depth:
            continue
        if ch == ';':
            s = ' '.join(stmt.split())
            stmt = ''
            if s.startswith('typedef') or 'inline' in s or 'LX_INLINE' in s:
                continue
            m = re.match(r'^[A-Za-z_][\w\s\*]*?\b(lx_\w+)\s*\(', s)
            if m and '(*' not in s.split(m.group(1))[0]:
                names.append(m.group(1))
            continue
        stmt += ch
    out = []
    for n in names:
        if n not in out and n not in EXCLUDE:
            out.append(n)
    return out


def main():
    names = functions(open(HEADER, encoding='utf-8').read())
    body = ['/* Generated by tools/gen_script_api.py from include/luxora/luxora.h - do not edit. */']
    body += ['LX_API_FN(%s)' % n for n in sorted(names)]
    text = '\n'.join(body) + '\n'
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old != text:
            print('src/script/script_api_table.h is out of date: run python3 tools/gen_script_api.py')
            sys.exit(1)
        print('script API table up to date (%d functions)' % len(names))
        return
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote %s (%d functions)' % (OUT, len(names)))


if __name__ == '__main__':
    main()
