#!/usr/bin/env python3
"""Bake the UI fonts (editor + game UI) into src/gfx/font_atlas.h (a grayscale PNG + glyph metrics).

Fonts: Inter (SIL OFL 1.1) and DejaVu Sans Mono (Bitstream Vera licence); licences in third_party/fonts.
Requires Pillow. Usage: python3 tools/bake_fonts.py
"""
import io, os
from PIL import Image, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INTER = "/usr/share/fonts/opentype/inter/"
FONTS = [  # (name, file, px at 1x)
    ("body", INTER + "Inter-Regular.otf", 14),
    ("bold", INTER + "Inter-SemiBold.otf", 14),
    ("small", INTER + "Inter-Regular.otf", 12),
    ("title", INTER + "Inter-SemiBold.otf", 22),
    ("mono", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 13),
]
CHARS = [chr(c) for c in range(32, 127)] + list("•…—×✓←→↑↓▲▼▶◀°±·")

def bake(scale):
    glyphs = []  # (font_index, char, img, xoff, yoff, adv)
    metrics = []
    for fi, (name, path, px) in enumerate(FONTS):
        size = px * scale
        f = ImageFont.truetype(path, size)
        ascent, descent = f.getmetrics()
        metrics.append((ascent, descent, ascent + descent))
        for ch in CHARS:
            if ch != " " and f.getmask(ch).getbbox() is None:
                continue
            bbox = f.getbbox(ch)
            adv = f.getlength(ch)
            if bbox is None or bbox[2] <= bbox[0]:
                glyphs.append((fi, ch, None, 0, 0, adv))
                continue
            w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
            img = Image.new("L", (w, h), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=f, fill=255)
            glyphs.append((fi, ch, img, bbox[0], bbox[1], adv))
    # shelf pack
    W = 512 * scale
    x, y, row = 4, 4, 0
    placed = []
    order = sorted(range(len(glyphs)), key=lambda i: -(glyphs[i][2].size[1] if glyphs[i][2] else 0))
    pos = {}
    for i in order:
        img = glyphs[i][2]
        if img is None:
            pos[i] = (0, 0, 0, 0)
            continue
        w, h = img.size
        if x + w + 2 > W:
            x, y, row = 4, y + row + 2, 0
        pos[i] = (x, y, w, h)
        x += w + 2
        row = max(row, h)
    H = 1
    while H < y + row + 4:
        H *= 2
    atlas = Image.new("L", (W, H), 0)
    atlas.paste(255, (0, 0, 3, 3))  # solid white texel block for shapes at (1,1)
    for i, (fi, ch, img, xo, yo, adv) in enumerate(glyphs):
        if img is not None:
            atlas.paste(img, pos[i][:2])
    buf = io.BytesIO()
    atlas.save(buf, "PNG", optimize=True)
    return buf.getvalue(), W, H, glyphs, pos, metrics

def main():
    out = ["/* Generated by tools/bake_fonts.py - do not edit. Inter (OFL) + DejaVu Sans Mono. */",
           "#ifndef LX_FONT_ATLAS_H", "#define LX_FONT_ATLAS_H", "#include <stdint.h>", "",
           f"#define LX_FONT_COUNT {len(FONTS)}",
           "/* LxBakedGlyph / LxBakedFont are declared in lx_internal.h */", ""]
    for scale in (1, 2):
        png, W, H, glyphs, pos, metrics = bake(scale)
        out.append(f"static const unsigned char lx_font_png_{scale}x[] = {{")
        for i in range(0, len(png), 24):
            out.append("    " + ",".join(str(b) for b in png[i:i+24]) + ",")
        out.append("};")
        out.append(f"static const LxBakedFont lx_fonts_{scale}x[LX_FONT_COUNT] = {{")
        for a, d, lh in metrics:
            out.append(f"    {{{a}, {d}, {lh}}},")
        out.append("};")
        out.append(f"static const LxBakedGlyph lx_glyphs_{scale}x[] = {{")
        for i, (fi, ch, img, xo, yo, adv) in enumerate(glyphs):
            x, y, w, h = pos[i]
            out.append(f"    {{{ord(ch)}, {fi}, {x}, {y}, {w}, {h}, {xo}, {yo}, {adv:.3f}f}},")
        out.append("};")
        out.append(f"#define LX_GLYPH_COUNT_{scale}X {len(glyphs)}")
        out.append("")
        print(f"{scale}x: atlas {W}x{H}, png {len(png)} bytes, {len(glyphs)} glyphs")
    out.append("#endif")
    open(os.path.join(ROOT, "src", "gfx", "font_atlas.h"), "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
