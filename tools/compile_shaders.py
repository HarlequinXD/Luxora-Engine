#!/usr/bin/env python3
"""Compile Luxora's GLSL shaders to SPIR-V and embed them in src/gfx/shaders_spv.h.

The generated header is committed, so building the engine never needs a shader compiler.
Run this after editing anything in shaders/:
    python3 tools/compile_shaders.py [path/to/glslangValidator]
"""
import os, shutil, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "shaders")
OUT = os.path.join(ROOT, "src", "gfx", "shaders_spv.h")

def find_compiler():
    if len(sys.argv) > 1:
        return sys.argv[1]
    for name in ("glslangValidator", "glslang"):
        p = shutil.which(name)
        if p:
            return p
    sys.exit("glslangValidator not found (install glslang-tools or the Vulkan SDK)")

def expand(text, common, depth=0):
    """#pragma lx_common inserts scene_common.glsl; #pragma lx_include <file> inserts shaders/<file>."""
    out = []
    for line in text.split("\n"):
        t = line.strip()
        if t == "#pragma lx_common":
            out.append(common)
        elif t.startswith("#pragma lx_include ") and depth < 8:
            inc = t.split(None, 2)[2].strip()
            out.append(expand(open(os.path.join(SRC, inc)).read(), common, depth + 1))
        else:
            out.append(line)
    return "\n".join(out)

def main():
    glslang = find_compiler()
    common = open(os.path.join(SRC, "scene_common.glsl")).read()
    shaders = sorted(f for f in os.listdir(SRC) if f.endswith((".vert", ".frag", ".comp")))
    lines = ["/* Generated by tools/compile_shaders.py - do not edit. */",
             "#ifndef LX_SHADERS_SPV_H", "#define LX_SHADERS_SPV_H", "#include <stdint.h>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name in shaders:
            text = expand(open(os.path.join(SRC, name)).read(), common)
            src = os.path.join(tmp, name)
            open(src, "w").write(text)
            spv = src + ".spv"
            r = subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-o", spv, src],
                               capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"{name} failed:\n{r.stdout}{r.stderr}")
            data = open(spv, "rb").read()
            words = struct.unpack(f"<{len(data)//4}I", data)
            ident = "lx_spv_" + name.replace(".", "_")
            lines.append(f"static const uint32_t {ident}[] = {{")
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i+8]) + ",")
            lines.append("};")
            lines.append("")
            print(f"  {name}: {len(data)} bytes")
    lines.append("#endif")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"wrote {OUT}")

if __name__ == "__main__":
    main()
